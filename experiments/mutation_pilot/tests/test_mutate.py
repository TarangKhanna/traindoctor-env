"""Offline tests of the mutation generator. Rules enforced (not current output):
  R1 determinism: the same (seed, op, variant) yields byte-identical mutant definitions and materialized trees.
  R2 a bug patch applies exactly once per edit; gold restores the pristine bytes; alt/decoy apply to the buggy text.
  R3 every arm is valid Python / parseable config; no arm equals another arm's text (a decoy is not a gold, etc.).
  R4 seeds outside 40000-40099 are refused (no overlap with DEV/TRAIN/sealed TEST ranges).
"""
import ast
import itertools
import sys
import tempfile
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from generator.mutate import OPERATORS, VARIANTS, apply_arm, make_mutant, materialize  # noqa: E402
from jobs.build import TEMPLATE  # noqa: E402
from jobs.config import loads  # noqa: E402

COMBOS = [(40000 + i, op, v) for i, (op, v) in enumerate(itertools.product(OPERATORS, VARIANTS))]


def _tree(d: Path) -> dict:
    return {str(p.relative_to(d)): p.read_bytes() for p in sorted((d / "job").glob("*")) if p.is_file()}


def _mat(m, arm=None):
    tmp = tempfile.TemporaryDirectory()
    jd = Path(tmp.name) / "j"
    materialize(jd, m.spec.config, m.bug)
    if arm:
        apply_arm(jd, m, arm)
    return tmp, jd


@pytest.mark.parametrize("seed,op,v", COMBOS)
def test_byte_determinism(seed, op, v):
    a, b = make_mutant(seed, op, v), make_mutant(seed, op, v)
    assert a.describe() == b.describe() and a.digest() == b.digest()
    t1, j1 = _mat(a)
    t2, j2 = _mat(b)
    assert _tree(j1) == _tree(j2)
    t1.cleanup(), t2.cleanup()


@pytest.mark.parametrize("seed,op,v", COMBOS)
def test_gold_restores_pristine_bytes(seed, op, v):
    m = make_mutant(seed, op, v)
    t, jd = _mat(m, "gold")
    tree, pristine = _tree(jd), {p.name: p.read_bytes() for p in TEMPLATE.glob("*.py") if p.name != "__init__.py"}
    for name, blob in pristine.items():
        assert tree[f"job/{name}"] == blob, f"gold did not restore {name}"
    # the config is regenerated by materialize from the same dict, so it is pristine too
    assert loads(tree["job/config.yaml"].decode()) == m.spec.config
    t.cleanup()


@pytest.mark.parametrize("seed,op,v", COMBOS)
def test_bug_changes_the_job_and_every_arm_is_valid_python(seed, op, v):
    m = make_mutant(seed, op, v)
    pristine = {p.name: p.read_text() for p in TEMPLATE.glob("*.py")}
    tb, jb = _mat(m)
    broken = _tree(jb)
    assert any(broken[f"job/{n}"].decode() != t for n, t in pristine.items() if f"job/{n}" in broken), "bug is a no-op"
    arms = {"noop": broken}
    for arm in ("gold", "decoy") + (("alt",) if m.alt else ()):
        t, jd = _mat(m, arm)
        arms[arm] = _tree(jd)
        t.cleanup()
    for arm, tree in arms.items():
        for name, blob in tree.items():
            if name.endswith(".py"):
                ast.parse(blob.decode(), name)
    # arms are pairwise distinct trees
    for a, b in itertools.combinations(arms, 2):
        assert arms[a] != arms[b], f"{a} and {b} produce the same job"
    tb.cleanup()


def test_every_operator_has_a_decoy_and_the_alt_policy_is_explicit():
    for seed, op, v in COMBOS:
        m = make_mutant(seed, op, v)
        assert m.decoy and m.decoy_note
        assert (m.alt is None) == m.alt_note.startswith("none:")


def test_task_a_only_for_o1_and_kill_plans():
    for seed, op, v in COMBOS:
        m = make_mutant(seed, op, v)
        assert m.spec.task == ("A" if op == "O1" else "B")
        assert (m.spec.kill is None) == (op == "O1")
        if op == "O3":
            assert m.spec.kill == (0, 7)      # writer rank killed right after the step-8 manifest hand-off
        if m.spec.kill:
            assert m.spec.kill[1] in (5, 6, 7, 9, 10) and 0 <= m.spec.kill[0] < m.spec.config["world_size"]


@pytest.mark.parametrize("seed", [39999, 40100, 10000, 12345, 0])
def test_seed_range_is_enforced(seed):
    with pytest.raises(AssertionError):
        make_mutant(seed, "O1", "a")
